/* Differential test of the C printer (Aeneas/Deep/CPrint.lean) on the hand-written deep
   terms of Aeneas/Deep/Tests.lean: `tests.c` is generated by `#deep_c` (see run.sh), and
   the expected values are those of the `reducesOn`/`execOn` checks of Tests.lean. */
#include <stdio.h>
#include "tests.c"

/* `incr` is in the closed world of the tests but has no deep term: the shallow `x + 1` */
int incr(uint32_t x, uint32_t *out) {
  if (__builtin_add_overflow(x, 1u, out)) return AENEAS_INTEGER_OVERFLOW;
  return AENEAS_OK;
}

static int failures = 0;
#define CHECK(cond, name) \
  do { if (cond) printf("ok   %s\n", name); else { printf("FAIL %s\n", name); failures++; } } while (0)

int main(void) {
  uint32_t u; int32_t i; int rc;
  rc = mul2_add1(3, &u);              CHECK(rc == 0 && u == 7, "mul2_add1 3 = 7");
  rc = mul2_add1(0x80000000u, &u);    CHECK(rc == AENEAS_INTEGER_OVERFLOW, "mul2_add1 2^31 overflows");
  rc = use_mul2_add1(3, 4, &u);       CHECK(rc == 0 && u == 11, "use_mul2_add1 3 4 = 11");
  rc = i32_id(2, &i);                 CHECK(rc == 0 && i == 2, "i32_id 2 = 2");
  rc = sum(4, &u);                    CHECK(rc == 0 && u == 12, "sum 4 = 12");
  rc = sum(0, &u);                    CHECK(rc == 0 && u == 0, "sum 0 = 0");
  rc = lift_add(6, 3, &u);            CHECK(rc == 0 && u == 2, "lift_add 6 3 = 2");
  Pair__u32_u32 p = mk_pair(1, 2);
  CHECK(pair_fst(p) == 1, "pair_fst (1,2) = 1");
  rc = pair_sum(p, &u);               CHECK(rc == 0 && u == 3, "pair_sum (1,2) = 3");
  rc = pair_sum_mono(p, &u);          CHECK(rc == 0 && u == 3, "pair_sum_mono (1,2) = 3");
  option__u32 none = { .tag = 0 }, some1 = { .tag = 1, .u.v1 = { 1 } };
  CHECK(opt_or(none, 5) == 5, "opt_or none 5 = 5");
  CHECK(opt_or(some1, 5) == 1, "opt_or (some 1) 5 = 1");
  arr_u32_4 a = { { 0, 0, 0, 0 } }, b;
  rc = arr_incr(a, 1, &b);
  CHECK(rc == 0 && b.data[1] == 1 && b.data[0] == 0 && a.data[1] == 0,
        "arr_incr: element 1 incremented, original untouched");
  rc = arr_incr(a, 4, &b);            CHECK(rc == AENEAS_ARRAY_OUT_OF_BOUNDS, "arr_incr out of bounds");
  rc = arr_get(b, 1, &u);             CHECK(rc == 0 && u == 1, "arr_get");
  uint32_t buf[3] = { 1, 2, 3 };
  vec__u32 v = { buf, 3, 3 }, w;
  rc = vec_set(v, 2, 9, &w);          CHECK(rc == 0 && w.ptr[2] == 9 && w.len == 3, "vec_set in place");
  rc = vec_set(v, 3, 9, &w);          CHECK(rc == AENEAS_ARRAY_OUT_OF_BOUNDS, "vec_set out of bounds");
  rc = use_incr();                    CHECK(rc == 0, "use_incr");
  printf("%d failure(s)\n", failures);
  return failures;
}
