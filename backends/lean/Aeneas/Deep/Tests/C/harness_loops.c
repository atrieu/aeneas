/* Differential test of the C printer on a generated crate: the `loops` test of
   `tests/src/loops.rs` (its deep terms are in `tests/lean/Loops.lean`). `loops.c` is
   generated by `#deep_c` (see run_loops.sh); the expected values follow the Rust source. */
#include <stdio.h>
#include "loops.c"

/* The constant `CARRAY` of `copy_carray` is an array literal, a leaf for the compiler:
   the printer emits its prototype only, so the harness provides it */
arr_u32_2 copy_carray_CARRAY(void) { return (arr_u32_2){ { 0, 1 } }; }

static int failures = 0;
#define CHECK(cond, name) \
  do { if (cond) printf("ok   %s\n", name); else { printf("FAIL %s\n", name); failures++; } } while (0)

int main(void) {
  uint32_t u; int rc;
  rc = iter(10, &u);                      CHECK(rc == 0 && u == 10, "iter 10 = 10");
  rc = sum(10, &u);                       CHECK(rc == 0 && u == 90, "sum 10 = 90");
  rc = sum(100000, &u);                   CHECK(rc == AENEAS_INTEGER_OVERFLOW, "sum 100000 overflows");
  rc = sum_with_mut_borrows(10, &u);      CHECK(rc == 0 && u == 90, "sum_with_mut_borrows 10 = 90");
  rc = sum_with_shared_borrows(10, &u);   CHECK(rc == 0 && u == 110, "sum_with_shared_borrows 10 = 110 (i is incremented before the sum)");
  uint32_t buf[3] = { 1, 2, 3 };
  vec__u32 v = { buf, 3, 3 }, w;
  rc = clear(v, &w);
  CHECK(rc == 0 && w.len == 3 && w.ptr[0] == 0 && w.ptr[1] == 0 && w.ptr[2] == 0, "clear [1,2,3] = [0,0,0]");
  rc = ignore_input_mut_borrow(7, 3, &u); CHECK(rc == 0 && u == 7, "ignore_input_mut_borrow keeps a");
  rc = incr_ignore_input_mut_borrow(7, 3, &u);
  CHECK(rc == 0 && u == 8, "incr_ignore_input_mut_borrow increments a once");
  bool b;
  rc = issue500_1(false, &b);             CHECK(rc == 0 && b == false, "issue500_1 false = false");
  arr_u32_2 a = { { 7, 7 } }, a2;
  rc = copy_carray(a, &a2);               CHECK(rc == 0 && a2.data[0] == 0 && a2.data[1] == 1, "copy_carray = [0, 1]");
  printf("%d failure(s)\n", failures);
  return failures;
}
